export interface MobileNeteaseResponse {
  status: number;
  body: Record<string, any>;
  cookie: string[];
}

export interface MobileNeteaseOptions {
  crypto?: "" | "api" | "weapi" | "eapi";
  cookie?: string | Record<string, string>;
  domain?: string;
  realIP?: string;
  ua?: string;
}

export type MobileNeteaseRequest = (
  uri: string,
  data: Record<string, any>,
  options?: MobileNeteaseOptions,
) => Promise<MobileNeteaseResponse>;

export type MobileNeteaseRoute = (
  query: Record<string, any>,
  request: MobileNeteaseRequest,
) => Promise<MobileNeteaseResponse>;

const songUrlV1: MobileNeteaseRoute = (query, request) => {
  const data: Record<string, any> = {
    ids: `[${query.id}]`,
    level: query.level || "exhigh",
    encodeType: "flac",
  };
  if (data.level === "sky") data.immerseType = "c51";
  return request("/api/song/enhance/player/url/v1", data, { ...query, crypto: "eapi" });
};

const loginQrCreate: MobileNeteaseRoute = async (query) => {
  const qrurl = `https://music.163.com/login?codekey=${query.key}`;
  const qrimg = query.qrimg ? await QRCode.toDataURL(qrurl) : "";
  return {
    status: 200,
    body: { code: 200, data: { qrurl, qrimg } },
    cookie: [],
  };
};

const djProgramRoute: MobileNeteaseRoute = (query, request) =>
  request(
    "/api/dj/program/byradio",
    {
      radioId: query.rid,
      limit: query.limit || 30,
      offset: query.offset || 0,
      asc: query.asc === true || query.asc === "true" || query.asc === 1,
    },
    { ...query, crypto: "weapi" },
  );

